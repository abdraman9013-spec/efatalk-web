export function lessonByN(n: number) {
  return LEVEL0_LESSONS.find((row) => row.n === n) || null;
}

export function speakPool(unlocked: number[]) {
  return LEVEL0_LESSONS.filter((row) => unlocked.includes(row.n)).flatMap((row) => row.speak);
}

export function normAnswer(value: string) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[’']/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function quizCorrect(item: LessonQuiz, raw: string) {
  const got = normAnswer(raw);
  if (!got) return false;
  if (item.kind === "contains") return item.answers.some((needle) => got.includes(normAnswer(needle)));
  return item.answers.some((ok) => {
    const want = normAnswer(ok);
    if (!want) return false;
    if (got === want) return true;
    return want.length >= 4 && got.includes(want);
  });
}
